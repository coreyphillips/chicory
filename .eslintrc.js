const VISIBLE_COPY =
  'Visible copy belongs in Settings; carry meaning with glyphs and put words in accessibility props (REDESIGN.md rule 1)';

// A run of letters: a word, as opposed to a sign, a separator or a number.
const WORDS = '/[A-Za-z]{2,}/';

// A string that reaches the screen: a literal, or the fixed parts of a
// template, with a word in it.
const PROSE = `:matches(Literal[value=${WORDS}], TemplateElement[value.raw=${WORDS}])`;

// What a value passes through on its way to the screen and still arrives as
// itself: either side of a condition, an operand of `&&`, `||` or `??`, an
// element of an array, a part of a template, a cast.
const THROUGH =
  ':matches(ConditionalExpression, LogicalExpression, ArrayExpression, SequenceExpression, TemplateLiteral, TSAsExpression)';

// Where a value is drawn: a child of an element or a fragment, or one of the
// props a host draws as text of its own.
const CHILD = ':matches(JSXElement, JSXFragment) > JSXExpressionContainer';
const DRAWN_PROPS = '/^(placeholder|defaultValue|title)$/';
const DRAWN_PROP = `JSXAttribute[name.name=${DRAWN_PROPS}]`;

/**
 * `PROSE` reached from `holder` through up to three of `THROUGH`, so
 * `{busy ? 'Sending' : 'Send'}`, `{[a && 'Wait', 'Now']}` and a string in a
 * fragment are caught, while a string that is an argument, a key or a
 * comparison is not.
 */
const reaching = holder =>
  [0, 1, 2, 3].map(depth => ({
    selector: [holder, ...Array(depth).fill(THROUGH), PROSE].join(' > '),
    message: VISIBLE_COPY,
  }));

module.exports = {
  root: true,
  extends: '@react-native',
  overrides: [
    {
      // The canvas and everything drawn on it show data, never prose: no
      // words as JSX text, as a string or template child of an element or a
      // fragment (however it gets there), or in a prop drawn as text. Words
      // that arrive by name, such as `copy.*` or a `label`, are left to the
      // copy guard, which sees what is drawn and whether a settings-class
      // surface holds it.
      //
      // Tracks do not edit this file. The integrator lifts an exclusion
      // once the track that owns its files reports them clean.
      files: [
        'src/stage/**',
        'src/glyphs/**',
        'src/scenes/**',
        'src/screens/**',
        'src/components/**',
      ],
      excludedFiles: [
        // Settings-class surfaces keep their words (REDESIGN.md rule 2):
        // Settings and its screens, first-run network and device setup, the
        // recovery phrase, and creating or restoring a wallet. The new
        // wallet sheet's frame in src/stage/layers stays in: it draws only
        // the words it is handed.
        'src/scenes/settings/**',
        'src/screens/Settings.tsx',
        'src/screens/NetworkSettings.tsx',
        'src/screens/DeviceSetup.tsx',
        'src/components/RecoveryPhrase.tsx',
      ],
      rules: {
        'no-restricted-syntax': [
          'error',
          { selector: `JSXText[value=${WORDS}]`, message: VISIBLE_COPY },
          ...reaching(CHILD),
          { selector: `${DRAWN_PROP} > ${PROSE}`, message: VISIBLE_COPY },
          ...reaching(`${DRAWN_PROP} > JSXExpressionContainer`),
          {
            // A host field draws whatever it is given there, so there it
            // takes only a literal, which the rules above read.
            selector: `JSXOpeningElement[name.name='TextInput'] > ${DRAWN_PROP} > JSXExpressionContainer`,
            message: VISIBLE_COPY,
          },
        ],
      },
    },
  ],
};
